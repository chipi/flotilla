func TestOrphansCollisionsSymlinksAndStrayFiles(t *testing.T) {
	fleetDir, lib := fixture(t)
	exp, _ := expand(t, fleetDir, lib)
	if err := exp.Write(fleetDir); err != nil {
		t.Fatal(err)
	}
	if d := exp.Drift(fleetDir); len(d) != 0 {
		t.Fatalf("%v", d)
	}
	drift := func(want string) {
		t.Helper()
		if got := strings.Join(exp.Drift(fleetDir), "\n"); !strings.Contains(got, want) {
			t.Fatalf("drift lacks %q:\n%s", want, got)
		}
	}
	// a step removed from its flow: the manifest still lists its folder
	put(t, fleetDir, "flows/.generated", mustRead(t, filepath.Join(fleetDir, "flows/.generated"))+"chain-old\n")
	put(t, fleetDir, "chain-old/routine.yaml", "x")
	drift("chain-old: generated by a flow once and no longer a step")
	// a stray file and a stray folder beside routine.yaml
	put(t, fleetDir, "chain-act/notes.txt", "x")
	drift("chain-act/notes.txt: not generated")
	put(t, fleetDir, "chain-act/scratch/a", "x")
	drift("chain-act/scratch: a folder that is not a version")
	// a symlinked version folder and a symlinked routine folder
	if err := os.RemoveAll(filepath.Join(fleetDir, "chain-verify", "v1")); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(filepath.Join(fleetDir, "chain-monitor", "v1"), filepath.Join(fleetDir, "chain-verify", "v1")); err != nil {
		t.Fatal(err)
	}
	drift("chain-verify/v1: a symlink")
	if err := os.RemoveAll(filepath.Join(fleetDir, "chain-think")); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(filepath.Join(fleetDir, "chain-monitor"), filepath.Join(fleetDir, "chain-think")); err != nil {
		t.Fatal(err)
	}
	drift("chain-think: a symlink")
}

func TestAHandWrittenFolderIsNeverOverwritten(t *testing.T) {
	fleetDir, lib := fixture(t)
	put(t, fleetDir, "chain-act/routine.yaml", "hand-written")
	exp, _ := expand(t, fleetDir, lib)
	if d := strings.Join(exp.Drift(fleetDir), "\n"); !strings.Contains(d, "chain-act: a routine folder not in flows/.generated has this step's name") {
		t.Fatalf("%s", d)
	}
	if err := exp.Write(fleetDir); err == nil || !strings.Contains(err.Error(), "nothing written") {
		t.Fatalf("a flow never overwrites a hand-written folder: %v", err)
	}
	if got := mustRead(t, filepath.Join(fleetDir, "chain-act/routine.yaml")); got != "hand-written" {
		t.Fatal("overwritten")
	}
}

func TestADashValueAfterAFlagIsRefused(t *testing.T) {
	fleetDir, lib := fixture(t)
	put(t, lib, "drafter/v1/block.yaml", `block: drafter
version: 1
role: learn
description: Drafts.
consumes: {every: true}
emits: [detection]
hands_to: []
actions: {}
params:
  prefix: {kind: string, arg: --prefix}
  env_prefix: {kind: string, env: SOME_PREFIX, optional: true}
env: []
model: none
max_autonomy: record
timeout: 2m
every: 1h
command: python3 /opt/flotilla/ops/drafter.py
case_kind: sop_proposal
code: [ops/drafter.py]
`)
	for with, wantErr := range map[string]bool{"{prefix: -x}": true, "{prefix: x, env_prefix: -x}": false, "{prefix: x-y}": false} {
		put(t, fleetDir, "flows/learn.yaml", "learn:\n  - name: drafter\n    use: drafter@1\n    worker: ops-read\n    with: "+with+"\n")
		_, err := expand(t, fleetDir, lib)
		if (err != nil) != wantErr || (err != nil && !strings.Contains(err.Error(), "cannot start with a dash")) {
			t.Errorf("%s: err %v, want error %v", with, err, wantErr)
		}
	}
}
